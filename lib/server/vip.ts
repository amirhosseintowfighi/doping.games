// VIP perks on the Doping game servers. Each server pulls its list (SourceMod admins_simple.ini format)
// with its own token, typically from a one-minute cron next to srcds; after a change the panel also
// asks the servers over RCON to reload admins once their next pull has happened.
import { and, eq, isNotNull } from 'drizzle-orm';
import { audit } from './audit';
import { decryptSecret } from './crypto';
import { db, schema } from './db';
import { rcon } from './gameq';

/** SourceMod flags: a = reserved slot, o = custom1 (chat/scoreboard tag), p = custom2 (!ws / !knife). */
export const PERK_FLAGS = { slot: 'a', tag: 'o', skins: 'p' } as const;

/** SteamID64 → STEAM_1:Y:Z (the form every SourceMod version accepts in admins_simple.ini). */
export function steam2(id64: string): string {
  const account = BigInt(id64) - 76561197960265728n;
  return `STEAM_1:${account & 1n}:${account >> 1n}`;
}

export async function vipEntries() {
  const rows = await db.select({ u: schema.users }).from(schema.users)
    .innerJoin(schema.subscriptions, eq(schema.subscriptions.userId, schema.users.id))
    .where(and(isNotNull(schema.users.steamId), eq(schema.subscriptions.kind, 'pro'), eq(schema.subscriptions.status, 'active')));
  return rows
    .filter(({ u }) => !u.disabledAt)
    .map(({ u }) => ({
      steamId64: u.steamId!, steam2: steam2(u.steamId!), username: u.username,
      flags: (Object.keys(PERK_FLAGS) as (keyof typeof PERK_FLAGS)[]).filter((k) => u.perks[k]).map((k) => PERK_FLAGS[k]).join(''),
    }))
    .filter((e) => e.flags);
}

export function adminsSimple(list: Awaited<ReturnType<typeof vipEntries>>) {
  const safe = (s: string) => s.replace(/[^\w.-]/g, '');
  return [
    '// Doping VIP list, generated by the panel. Do not edit: the next pull overwrites it.',
    `// ${new Date().toISOString()} · ${list.length} players`,
    ...list.map((e) => `"${e.steam2}" "${e.flags}" // ${safe(e.username)}`),
    '',
  ].join('\n');
}

let timer: NodeJS.Timeout | null = null;
/** Debounced: ~75 s after the last change (one cron pull later), servers that pull the list reload admins. */
export function scheduleVipReload() {
  if (timer) clearTimeout(timer);
  timer = setTimeout(async () => {
    timer = null;
    const list = await db.select().from(schema.gameServers).where(and(isNotNull(schema.gameServers.vipTokenHash), isNotNull(schema.gameServers.rconPassEnc), eq(schema.gameServers.enabled, true)));
    for (const s of list) {
      try {
        await rcon(s.host, s.port, decryptSecret(s.rconPassEnc!, `server:${s.id}:rcon`), 'sm_reloadadmins');
      } catch (err) {
        await audit('rcon', 'warn', `sm_reloadadmins failed · ${s.name} · ${(err as Error).message}`, 'vip-sync');
      }
    }
  }, 75_000);
  timer.unref?.();
}
